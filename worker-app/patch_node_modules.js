const fs = require('fs');
const path = String.raw`x:\yello capp mern - Copy\worker-app\node_modules\react-native\ReactCommon\react\renderer\core\graphicsConversions.h`;

try {
    let content = fs.readFileSync(path, 'utf8');
    console.log('Original content length:', content.length);

    // 1. Ensure Header Check
    if (!content.includes('#include <folly/Format.h>')) {
        console.log('Adding header include');
        content = '#include <folly/Format.h>\n' + content;
    }

    // 2. Replace std::format with folly::sformat
    const targetCode = 'return folly::sformat("{}%", dimension.value);';

    if (content.includes(targetCode)) {
        console.log('File is already correctly patched with sformat.');
    } else {
        let replaced = false;
        const patterns = [
            'return std::format("{}%", dimension.value);',
            'return folly::format("{}%", dimension.value);'
        ];

        for (const pattern of patterns) {
            if (content.includes(pattern)) {
                content = content.replace(pattern, targetCode);
                console.log(`Replaced: ${pattern}`);
                replaced = true;
                break;
            }
        }

        if (!replaced) {
            console.warn('WARNING: Could not find target string to replace in node_modules!');
            // Check for context
            const lines = content.split('\n');
            // around line 81
            const start = Math.max(0, 75);
            const end = Math.min(lines.length, 90);
            console.log(lines.slice(start, end).join('\n'));

        } else {
            fs.writeFileSync(path, content);
            console.log('Successfully wrote patched content to node_modules.');
        }
    }

} catch (error) {
    console.error('CRITICAL ERROR:', error);
    process.exit(1);
}
